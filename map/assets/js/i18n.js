function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}

const LANGS = ['en', 'ka', 'ru'];
let lang = (() => {
  try {
    const saved = localStorage.getItem('hig:lang');
    if (LANGS.includes(saved)) return saved;
  } catch {}
  const browser = (navigator.language || 'en').toLowerCase().slice(0, 2);
  return LANGS.includes(browser) ? browser : 'en';
})();

export const getLang = () => lang;
export const localeOf = (l = lang) => ({ en: 'en-GB', ka: 'ka-GE', ru: 'ru-RU' })[l];
export const languages = LANGS;

export function setLang(next) {
  if (!LANGS.includes(next)) return;
  lang = next;
  try { localStorage.setItem('hig:lang', next); } catch {}
  document.documentElement.lang = next;
}

export function t(key, ...args) {
  const value = dict[lang][key] ?? dict.en[key];
  if (typeof value === 'function') return value(...args);
  return value ?? key;
}

document.documentElement.lang = lang;
